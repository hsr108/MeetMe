import mongoose from "mongoose";

// _id: false so $addToSet can de-duplicate { name, username } pairs.
const participantSchema = new mongoose.Schema(
  {
    name: { type: String, required: true },
    username: { type: String, default: null }, // null for guests
  },
  { _id: false }
);

// One continuous call in a room: first join → last leave. Written by the Socket.IO server.
const callSessionSchema = new mongoose.Schema({
  _id: { type: String }, // session id generated by the room store
  meetingCode: { type: String, required: true },
  startedAt: { type: Date, default: Date.now },
  endedAt: { type: Date, default: null },
  participants: { type: [participantSchema], default: [] },
});

const CallSession = mongoose.model("CallSession", callSessionSchema);

export { CallSession };
